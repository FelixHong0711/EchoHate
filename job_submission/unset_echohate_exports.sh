#!/usr/bin/env bash
# Clear echohate / baseline / abstract / cluster env overrides from the current shell.
# Usage (from any directory):
#   source experiment/echohate/job_submission/unset_echohate_exports.sh
# Or from experiment/echohate:
#   source job_submission/unset_echohate_exports.sh

_echohate_unset_list=(
  # Data paths & seeds
  DATA_ROOT OUTPUT_DIR ECHOHATE_DATA_ROOT ECHOHATE_DATA_SEED_DIR ECHOHATE_ROOT
  ECHOHATE_ROBERTA_BASELINE_DIR ECHOHATE_SPLITTED_DATA_SUBDIR
  CLUSTERED_SUBDIR ABSTRACTED_SUBDIR
  DATASET DATASETS ALL_DATASETS ONLY_DATASETS
  # LLM val/test + selected-hard
  MODEL_NAMES LLM_OUTPUT_FAMILY LLM_SPLITS SUBMIT_NOCONTEXT OUTPUT_TAG_SUFFIX
  ONLY_MODE PROFILE PROMPT_TASK NO_CACHE NO_GT_METRICS
  INPUT_CSV OUT_SUBDIR MAX_SAMPLES KEEP_MODELS_LOADED
  PHI_SELHARD_RSYNC_REL PHI_SELHARD_REMIND_DATA_SYNC PHI_SELHARD_DATA_ROOT
  PHI_SELHARD_OUTPUT_MODEL_TAG PHI_SELHARD_TRAILING_SUFFIX PHI_SELHARD_ONLY_SPEC
  LLM_INFER_HARD_OUTPUT_MODEL_TAG LLM_INFER_HARD_TRAILING_SUFFIX
  HPC_SKIP_CODE_RSYNC HPC_SKIP_VERIFY_SYNC HPC_SKIP_HF_TOKEN_RSYNC HPC_SKIP_PROJECT_ENV
  TEACHER_RSYNC_DATA RUN_TAG_SUFFIX
  # RNG / project config (shell exports from echohate_project_env.sh)
  RANDOM_STATE SEED ECHOHATE_CANONICAL_RANDOM_STATE
  ECHOHATE_SPLIT_SEED
  ECHOHATE_SEEDS_COMMA AMPLEHATE_SEED_LIST
  ECHOHATE_TRAIN_FRAC ECHOHATE_VALIDATION_FRAC ECHOHATE_TEST_FRAC
  # Training hyper (training_hyper_defaults.sh / sbatch)
  NUM_EPOCHS BATCH_SIZE EVAL_BATCH_SIZE LEARNING_RATE WEIGHT_DECAY WARMUP_RATIO
  MAX_LENGTH POS_WEIGHT_MODE CLASS_WEIGHT_TARGET PAD_TO_MAX_LENGTH NO_EVAL_EACH_EPOCH
  # Baseline / stage2
  MODEL_NAME CONDA_ENV CE_CONTRASTIVE_LAMBDA CONTRASTIVE_MARGIN
  TRACK_DYNAMICS SKIP_TEST_INFER
  TRAIN_ON_TRAIN_VAL EPOCHS_FROM_TRAIN_BASELINE TRAINVAL_APPLIED_THRESHOLD
  EPOCHS_FROM_METRIC_SUMMARY ECHOHATE_ROBERTA_TRAIN_BASELINE_DIR
  # Submit / sync toggles
  SYNC_ALL_DATA SYNC_FULL DATASET_SYNC_DIR REMOTE_DATASET_DIR
  # Abstract / cluster extras
  ABSTRACT_SCRIPT ABSTRACT_TASK CLUSTERED_SUBDIR ABSTRACTED_SUBDIR
  CONTEXT_PATH CONTEXT_DATASET CONTEXT_RETRIEVAL_MODE NO_CONTEXT
  CONTEXT_PATTERNS_PATH CONTEXT_DATASET CONTEXT_RETRIEVAL_MODE NO_CONTEXT RAG_PATTERNS_PATH RAG_DATASET RAG_RETRIEVAL_MODE NO_RAG
  TRAIN_PLUS_VALIDATION OFFENSIVE_BUCKETS SBATCH_EXTRA SBATCH_NODES
)

for _v in "${_echohate_unset_list[@]}"; do
  unset "${_v}" 2>/dev/null || true
done

# zsh: DATASETS is often a typed array — scalar unset is not enough.
if [ -n "${ZSH_VERSION:-}" ]; then
  unset DATASETS 2>/dev/null || true
  typeset -a DATASETS 2>/dev/null && unset DATASETS 2>/dev/null || true
fi

echo "[unset_echohate_exports] Cleared EchoHate job env overrides in this shell."
echo "  (HPC_USER, HPC_HOST, HPC_RA, HPC_PASSWORD left unchanged — unset manually if needed)"
